import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import ts from "typescript";

const root = process.cwd();
const arguments_ = process.argv.slice(2);
const baseRevision = valueAfter("--base") ?? "final";
const headRevision = valueAfter("--head") ?? "HEAD";
const outputPath = resolve(root, "docs/metrics/report.md");

function valueAfter(flag) {
  const index = arguments_.indexOf(flag);
  return index < 0 ? undefined : arguments_[index + 1];
}

function git(arguments__) {
  return execFileSync("git", arguments__, { cwd: root, encoding: "utf8" }).trimEnd();
}

function sourceFiles(revision, prefix) {
  return git(["ls-tree", "-r", "--name-only", revision, "--", prefix])
    .split(/\r?\n/)
    .filter((path) => path.endsWith(".ts"));
}

function readRevisionFile(revision, path) {
  return git(["show", `${revision}:${path}`]);
}

function nonBlankLines(source) {
  return source.split(/\r?\n/).filter((line) => line.trim().length > 0).length;
}

function category(path) {
  if (path === "src/main.ts" || path.startsWith("src/assembly/")) {
    return "Assembly";
  }
  if (path.startsWith("src/plugins/")) {
    return "Plugins";
  }
  return "Kernel";
}

function responsibility(path) {
  if (path === "src/main.ts") return "Process composition root";
  if (path.startsWith("src/assembly/")) return "Plugin context, loading, and code assembly";
  if (path.startsWith("src/plugins/")) return "Plugin implementations and built-in providers";
  if (path.startsWith("src/domain/")) return "Domain model and shape-provider contract";
  if (path.startsWith("src/application/")) return "Use cases, registries, commands, and application ports";
  if (path.startsWith("src/cli/")) return "REPL and command parsing";
  if (path.startsWith("src/infrastructure/")) return "SVG and filesystem adapters";
  return "CLI source";
}

function complexity(source, fileName) {
  const sourceFile = ts.createSourceFile(
    fileName,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  let total = 0;

  const visitFunction = (functionNode) => {
    if (functionNode.body === undefined) return;
    let score = 1;
    const visitDecision = (node) => {
      if (node !== functionNode && ts.isFunctionLike(node)) return;
      if (
        ts.isIfStatement(node)
        || ts.isConditionalExpression(node)
        || ts.isForStatement(node)
        || ts.isForInStatement(node)
        || ts.isForOfStatement(node)
        || ts.isWhileStatement(node)
        || ts.isDoStatement(node)
        || ts.isCatchClause(node)
        || (ts.isCaseClause(node) && node.expression !== undefined)
      ) {
        score += 1;
      }
      if (
        ts.isBinaryExpression(node)
        && [
          ts.SyntaxKind.AmpersandAmpersandToken,
          ts.SyntaxKind.BarBarToken,
          ts.SyntaxKind.QuestionQuestionToken,
        ].includes(node.operatorToken.kind)
      ) {
        score += 1;
      }
      ts.forEachChild(node, visitDecision);
    };
    visitDecision(functionNode.body);
    total += score;
  };

  const visit = (node) => {
    if (ts.isFunctionLike(node)) visitFunction(node);
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return total;
}

function measure(revision) {
  const files = sourceFiles(revision, "src");
  const totals = { Kernel: 0, Assembly: 0, Plugins: 0 };
  let totalComplexity = 0;
  const inventory = [];
  for (const path of files) {
    const source = readRevisionFile(revision, path);
    const area = category(path);
    const lines = nonBlankLines(source);
    totals[area] += lines;
    totalComplexity += complexity(source, path);
    inventory.push({ path, area, lines, responsibility: responsibility(path) });
  }
  const extensionFiles = sourceFiles(revision, "vscode-extension/src");
  const extensionInventory = extensionFiles.map((path) => ({
    path,
    lines: nonBlankLines(readRevisionFile(revision, path)),
  }));
  const extensionLines = extensionInventory.reduce((sum, file) => sum + file.lines, 0);
  return { totals, totalComplexity, inventory, extensionFiles, extensionInventory, extensionLines };
}

function tableRows(rows) {
  return rows.map(({ path, area, lines, responsibility: detail }) =>
    `| \`${path}\` | ${area} | ${lines} | ${detail} |`
  ).join("\n");
}

const base = measure(baseRevision);
const head = measure(headRevision);
const delta = head.totalComplexity - base.totalComplexity;
const report = [
  "# Phase 2 metrics",
  "",
  `Generated by \`node scripts/metrics.mjs --base ${baseRevision} --head ${headRevision}\`.`,
  "Counts come from tracked TypeScript source in the selected Git revisions; blank lines are excluded.",
  "Cyclomatic complexity is a syntax-based aggregate: one per function body plus branches, loops, non-default switch cases, catches, ternaries, and logical AND/OR/nullish operators.",
  "Dependencies, tests, and build output are excluded. The VS Code extension is listed separately and is not included in CLI deltas.",
  "",
  "## CLI source counts",
  "",
  "| Area | Base LOC | Phase 2 LOC |",
  "|---|---:|---:|",
  `| Kernel | ${base.totals.Kernel} | ${head.totals.Kernel} |`,
  `| Assembly | ${base.totals.Assembly} | ${head.totals.Assembly} |`,
  `| Plugins | ${base.totals.Plugins} | ${head.totals.Plugins} |`,
  `| **Total** | **${Object.values(base.totals).reduce((sum, value) => sum + value, 0)}** | **${Object.values(head.totals).reduce((sum, value) => sum + value, 0)}** |`,
  "",
  `Aggregate cyclomatic complexity: ${base.totalComplexity} -> ${head.totalComplexity} (increment ${delta >= 0 ? "+" : ""}${delta}).`,
  "",
  "## VS Code extension inventory (separate from CLI)",
  "",
  `TypeScript source files: ${head.extensionFiles.length}; non-blank LOC: ${head.extensionLines}.`,
  "",
  "| File | LOC | Responsibility |",
  "|---|---:|---|",
  ...head.extensionInventory.map(({ path, lines }) =>
    `| \`${path}\` | ${lines} | VS Code extension activation, providers, and SVG outline parsing |`
  ),
  "",
  "## CLI file inventory and responsibilities",
  "",
  "| File | Area | LOC | Responsibility |",
  "|---|---|---:|---|",
  tableRows(head.inventory),
  "",
].join("\n");

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, report, "utf8");
console.log(`Wrote ${relative(root, outputPath)} for ${baseRevision}..${headRevision}.`);
